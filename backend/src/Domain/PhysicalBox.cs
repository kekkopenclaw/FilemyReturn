namespace DocuArchive.Domain;

/// <summary>
/// A physical storage box (Phase 7 physical archive): the real-world home of
/// paper originals — a box on a shelf, in a cupboard, in an off-site store.
/// A box belongs to one workspace; a document can sit in at most one box at a
/// time (<see cref="Document.PhysicalBoxId"/>). The printed label carries the
/// box's <see cref="Code"/> and a QR code that deep-links to the box in the
/// app (<c>/boxes?box={Code}</c>), so scanning a shelf finds the box and its
/// documents. Names are unique per workspace (case-insensitive — enforced in
/// the service; the database index guards exact duplicates and races). Codes
/// are globally unique (unique index) and generated by the service.
/// </summary>
public class PhysicalBox
{
    public Guid Id { get; set; } = Guid.NewGuid();
    public Guid WorkspaceId { get; set; }
    public Workspace? Workspace { get; set; }
    public required string Name { get; set; }
    /// <summary>Short human-readable code printed on the label, e.g. "BOX-7K2P9Q". Globally unique.</summary>
    public required string Code { get; set; }
    /// <summary>Where the box physically lives, e.g. "Shelf B, row 3" or "Loft, north wall".</summary>
    public required string Location { get; set; }
    public string? Description { get; set; }
    public DateTime CreatedAt { get; set; } = DateTime.UtcNow;

    public ICollection<Document> Documents { get; set; } = new List<Document>();
}
